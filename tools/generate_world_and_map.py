#!/usr/bin/env python3
"""
Generate the Gazebo world and a ground-truth occupancy map from ONE geometry list.

Outputs (paths relative to the repo root):
  src/tb3_nav_demo/worlds/cluttered_room.sdf.xacro
  src/tb3_nav_demo/maps/cluttered_room.pgm
  src/tb3_nav_demo/maps/cluttered_room.yaml

Frame convention: map frame == Gazebo world frame (same origin, same axes).
The robot spawns at (-2.0, -0.5, yaw 0), the default in nav2_minimal_tb3_sim's
spawn_tb3.launch.py, so the world is laid out around that pose.

Pure Python, no third-party dependencies. Run from the repo root:
  python3 tools/generate_world_and_map.py
"""

import math
import os

# ---------------------------------------------------------------- geometry
# Room interior: x in [-3.5, 3.5], y in [-2.5, 2.5]  (7 m x 5 m).
# All objects are static and 0.5 m tall; the lidar scans at about 0.17 m.
HEIGHT = 0.5
WALL_T = 0.15

# (name, centre_x, centre_y, size_x, size_y)
BOXES = [
    # Outer walls (outside the 7 x 5 m interior)
    ('wall_north', 0.0, 2.5 + WALL_T / 2, 7.0 + 2 * WALL_T, WALL_T),
    ('wall_south', 0.0, -2.5 - WALL_T / 2, 7.0 + 2 * WALL_T, WALL_T),
    ('wall_east', 3.5 + WALL_T / 2, 0.0, WALL_T, 5.0),
    ('wall_west', -3.5 - WALL_T / 2, 0.0, WALL_T, 5.0),
    # Dividing wall, 1.0 m thick (x 0.5..1.5), with ONE gap at y 0.6..1.5.
    # That gap is the narrow corridor: 0.9 m wide, 1.0 m long.
    # It is the only way between the west (cluttered) and east halves.
    ('divider_south', 1.0, -0.95, 1.0, 3.1),   # y -2.5 .. 0.6
    ('divider_north', 1.0, 2.0, 1.0, 1.0),     # y  1.5 .. 2.5
    # Clutter, west half
    ('box_nw', -2.6, 1.3, 0.6, 0.6),
    ('box_long', -0.9, -1.4, 0.4, 1.2),
    ('box_mouth', -0.3, 1.9, 0.5, 0.5),        # near the corridor entrance
    # East half
    ('box_east', 3.1, -0.6, 0.6, 0.6),
]

# (name, centre_x, centre_y, radius)
CYLINDERS = [
    ('cyl_centre', -1.2, 0.6, 0.20),
    ('cyl_sw', -2.9, -1.8, 0.25),
    ('cyl_ne', 2.6, 1.6, 0.25),
]

# Map raster
RESOLUTION = 0.05            # m/cell, same as the Nav2 costmaps
MARGIN = 0.25                # unknown border around the outer walls
X_MIN, X_MAX = -3.5 - WALL_T - MARGIN, 3.5 + WALL_T + MARGIN
Y_MIN, Y_MAX = -2.5 - WALL_T - MARGIN, 2.5 + WALL_T + MARGIN

FREE, OCCUPIED, UNKNOWN = 254, 0, 205   # map_server trinary, negate: 0

# ------------------------------------------------------------------ helpers


def inside_box(x, y, b):
    _, cx, cy, sx, sy = b
    return abs(x - cx) <= sx / 2 and abs(y - cy) <= sy / 2


def inside_cylinder(x, y, c):
    _, cx, cy, r = c
    return math.hypot(x - cx, y - cy) <= r


def occupied(x, y):
    return any(inside_box(x, y, b) for b in BOXES) or \
        any(inside_cylinder(x, y, c) for c in CYLINDERS)


def inside_room(x, y):
    return -3.5 <= x <= 3.5 and -2.5 <= y <= 2.5


def model_box(name, cx, cy, sx, sy):
    colour = '0.55 0.55 0.6 1' if name.startswith(('wall', 'divider')) else '0.85 0.45 0.2 1'
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{cx} {cy} {HEIGHT / 2} 0 0 0</pose>
      <link name="link">
        <collision name="collision">
          <geometry><box><size>{sx} {sy} {HEIGHT}</size></box></geometry>
        </collision>
        <visual name="visual">
          <geometry><box><size>{sx} {sy} {HEIGHT}</size></box></geometry>
          <material><ambient>{colour}</ambient><diffuse>{colour}</diffuse></material>
        </visual>
      </link>
    </model>"""


def model_cylinder(name, cx, cy, r):
    colour = '0.2 0.5 0.85 1'
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{cx} {cy} {HEIGHT / 2} 0 0 0</pose>
      <link name="link">
        <collision name="collision">
          <geometry><cylinder><radius>{r}</radius><length>{HEIGHT}</length></cylinder></geometry>
        </collision>
        <visual name="visual">
          <geometry><cylinder><radius>{r}</radius><length>{HEIGHT}</length></cylinder></geometry>
          <material><ambient>{colour}</ambient><diffuse>{colour}</diffuse></material>
        </visual>
      </link>
    </model>"""


# Header copied from nav2_minimal_tb3_sim 1.0.1 worlds/tb3_sandbox.sdf.xacro:
# same system plugins, same 'headless' xacro arg (tb3_simulation_launch.py passes it),
# same world name 'default'. Only the turtlebot3_world model include is replaced.
WORLD_HEADER = """<?xml version="1.0"?>
<!-- GENERATED by tools/generate_world_and_map.py. Edit the script, not this file. -->
<sdf version="1.6" xmlns:xacro="http://www.ros.org/wiki/xacro">
  <xacro:arg name="headless" default="true"/>

  <world name="default">
    <plugin
      filename="gz-sim-physics-system"
      name="gz::sim::systems::Physics">
    </plugin>
    <plugin
      filename="gz-sim-user-commands-system"
      name="gz::sim::systems::UserCommands">
    </plugin>
  <xacro:unless value="$(arg headless)">
    <plugin
      filename="gz-sim-scene-broadcaster-system"
      name="gz::sim::systems::SceneBroadcaster">
    </plugin>
  </xacro:unless>
    <plugin
      filename="gz-sim-sensors-system"
      name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin
      filename="gz-sim-imu-system"
      name="gz::sim::systems::Imu">
    </plugin>

    <light name='sun' type='directional'>
        <cast_shadows>0</cast_shadows>
        <pose>0 0 10 0 0 0</pose>
        <diffuse>0.8 0.8 0.8 1</diffuse>
        <specular>0.8 0.8 0.8 1</specular>
        <attenuation>
            <range>1000</range>
            <constant>0.9</constant>
            <linear>0.01</linear>
            <quadratic>0.001</quadratic>
        </attenuation>
        <direction>-0.5 0.1 -0.9</direction>
    </light>
    <model name='ground_plane'>
        <static>1</static>
        <link name='link'>
            <collision name='collision'>
                <geometry>
                    <plane>
                        <normal>0 0 1</normal>
                        <size>100 100</size>
                    </plane>
                </geometry>
                <max_contacts>10</max_contacts>
            </collision>
            <visual name='visual'>
                <geometry>
                    <plane>
                        <normal>0 0 1</normal>
                        <size>100 100</size>
                    </plane>
                </geometry>
                <material>
                    <ambient>0.8 0.8 0.8 1</ambient>
                    <diffuse>0.8 0.8 0.8 1</diffuse>
                    <specular>0.8 0.8 0.8 1</specular>
                </material>
            </visual>
        </link>
    </model>
    <scene>
      <shadows>0</shadows>
    </scene>
    <physics name='3ms' type='ode'>
        <max_step_size>0.003</max_step_size>
        <real_time_factor>1</real_time_factor>
    </physics>
"""

WORLD_FOOTER = """
  </world>
</sdf>
"""


def write_world(path):
    body = ''.join(model_box(*b) for b in BOXES) + \
        ''.join(model_cylinder(*c) for c in CYLINDERS)
    with open(path, 'w') as f:
        f.write(WORLD_HEADER + body + WORLD_FOOTER)


def write_map(pgm_path, yaml_path):
    w = round((X_MAX - X_MIN) / RESOLUTION)
    h = round((Y_MAX - Y_MIN) / RESOLUTION)
    rows = []
    for r in range(h):                       # PGM row 0 is the TOP (max y)
        y = Y_MAX - (r + 0.5) * RESOLUTION
        row = bytearray()
        for c in range(w):
            x = X_MIN + (c + 0.5) * RESOLUTION
            if occupied(x, y):
                row.append(OCCUPIED)
            elif inside_room(x, y):
                row.append(FREE)
            else:
                row.append(UNKNOWN)
        rows.append(bytes(row))
    with open(pgm_path, 'wb') as f:
        f.write(f'P5\n# generated by tools/generate_world_and_map.py\n{w} {h}\n255\n'.encode())
        f.write(b''.join(rows))
    with open(yaml_path, 'w') as f:
        f.write(
            '# Ground-truth map rasterised from the world geometry by\n'
            '# tools/generate_world_and_map.py. Map frame == Gazebo world frame.\n'
            '# README "Map" explains how to replace it with a slam_toolbox map.\n'
            f'image: {os.path.basename(pgm_path)}\n'
            'mode: trinary\n'
            f'resolution: {RESOLUTION}\n'
            f'origin: [{X_MIN:.3f}, {Y_MIN:.3f}, 0.0]\n'
            'negate: 0\n'
            'occupied_thresh: 0.65\n'
            'free_thresh: 0.25\n')
    return w, h


if __name__ == '__main__':
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    pkg = os.path.join(root, 'src', 'tb3_nav_demo')
    os.makedirs(os.path.join(pkg, 'worlds'), exist_ok=True)
    os.makedirs(os.path.join(pkg, 'maps'), exist_ok=True)
    write_world(os.path.join(pkg, 'worlds', 'cluttered_room.sdf.xacro'))
    w, h = write_map(os.path.join(pkg, 'maps', 'cluttered_room.pgm'),
                     os.path.join(pkg, 'maps', 'cluttered_room.yaml'))
    print(f'world + map written ({w}x{h} cells @ {RESOLUTION} m)')
